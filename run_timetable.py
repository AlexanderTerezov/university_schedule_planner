"""Run the timetable optimizer and export the results to Excel.

Usage:
    python run_timetable.py
    python run_timetable.py input.xlsx timetable.xlsx
"""

import sys
from collections import Counter

import pandas as pd
from openpyxl import load_workbook
from openpyxl.styles import Font
from openpyxl.utils import get_column_letter

import config
import importer
import model


def clock(minutes):
    """Convert minutes since midnight to HH:MM."""
    return f"{minutes // 60:02d}:{minutes % 60:02d}"


def format_workbook(path):
    wb = load_workbook(path)

    for ws in wb:
        ws.freeze_panes = "A2"
        ws.auto_filter.ref = ws.dimensions

        for cell in ws[1]:
            cell.font = Font(bold=True)

        for column in ws.columns:
            width = max(
                len(str(cell.value)) if cell.value is not None else 0
                for cell in column
            )
            letter = get_column_letter(column[0].column) # pyright: ignore[reportArgumentType]
            ws.column_dimensions[letter].width = min(max(width + 2, 10), 60)

    wb.save(path)


def main(input_path=config.INPUT_FILE, output_path="timetable.xlsx"):
    print("1/5 Importing courses...")

    courses, issues, rows_read = importer.load_courses(input_path)
    sessions = importer.expand_sessions(courses)

    if not sessions:
        raise RuntimeError(
            "No sessions were imported. Check the input workbook and "
            "the Issues sheet generated by run_import.py."
        )

    print(f"   Courses: {len(courses)}")
    print(f"   Sessions: {len(sessions)}")
    print(f"   Total teaching hours: {sum(s.length for s in sessions)}")

    print("\n2/5 Solving the timetable...")

    placements, stats = model.solve_flexible(sessions)

    for line in stats.get("repair", []):
        print(f"   Repair {line}")

    print("\n3/5 Verifying hard constraints...")

    validation_problems = model.verify(placements)

    scheduled = [p for p in placements if p.scheduled]
    unscheduled = [p for p in placements if not p.scheduled]

    print(f"   Scheduled: {len(scheduled)} / {len(placements)} sessions")
    print(f"   Unscheduled: {len(unscheduled)}")
    print(f"   Validation problems: {len(validation_problems)}")

    timetable_rows = []
    unscheduled_rows = []

    for p in placements:
        s = p.session
        c = s.course

        common = {
            "Type": c.kind,
            "Subject": c.subject,
            "Cohorts": ", ".join(c.cohorts),
            "Group": s.group,
            "Part": s.part + 1,
            "Duration (hours)": s.length,
            "Teachers": ", ".join(s.teachers),
        }

        if p.scheduled:
            timetable_rows.append({
                **common,
                "Date": p.date,
                "Weekday": p.date.strftime("%A"),
                "Start": clock(p.start),
                "End": clock(p.end),
                "Room": p.room or "NOT ASSIGNED",
                "Preference warnings": "; ".join(p.unmet),
            })
        else:
            unscheduled_rows.append({
                **common,
                "Reason": "Solver could not place this session "
                          "within the constraints and time limit.",
            })

    timetable_df = pd.DataFrame(timetable_rows)
    if not timetable_df.empty:
        timetable_df = timetable_df.sort_values(
            ["Date", "Start", "Room", "Subject"]
        ).reset_index(drop=True)

    unscheduled_df = pd.DataFrame(unscheduled_rows)

    validation_df = pd.DataFrame({
        "Validation problem": validation_problems
    })

    issues_df = pd.DataFrame(
        [vars(issue) for issue in issues],
        columns=["level", "sheet", "row", "subject", "message"],
    )

    stats_df = pd.DataFrame([
        {"Metric": "Solver status", "Value": stats["status"]},
        {"Metric": "Objective penalty", "Value": stats["objective"]},
        {"Metric": "Best objective bound", "Value": stats["bound"]},
        {"Metric": "Solver time (seconds)", "Value": stats["seconds"]},
        {"Metric": "Input rows read", "Value": str(dict(rows_read))},
        {"Metric": "Courses imported", "Value": len(courses)},
        {"Metric": "Sessions generated", "Value": len(placements)},
        {"Metric": "Length repair rounds", "Value": "; ".join(stats.get("repair", [])) or "none needed"},
        {"Metric": "Sessions scheduled", "Value": len(scheduled)},
        {"Metric": "Sessions unscheduled", "Value": len(unscheduled)},
        {"Metric": "Validation problems", "Value": len(validation_problems)},
        {"Metric": "Import issues", "Value": len(issues)},
    ])

    print("\n4/5 Writing Excel workbook...")

    with pd.ExcelWriter(output_path, engine="openpyxl") as writer:
        timetable_df.to_excel(
            writer, sheet_name="Timetable", index=False
        )
        unscheduled_df.to_excel(
            writer, sheet_name="Unscheduled", index=False
        )
        validation_df.to_excel(
            writer, sheet_name="Validation", index=False
        )
        issues_df.to_excel(
            writer, sheet_name="Import Issues", index=False
        )
        stats_df.to_excel(
            writer, sheet_name="Solver Stats", index=False
        )

    format_workbook(output_path)

    print("\n5/5 Finished.")
    print(f"   Output: {output_path}")
    print(f"   Solver status: {stats['status']}")
    print(f"   Scheduled sessions: {len(scheduled)}/{len(placements)}")

    if validation_problems:
        print("\nWARNING: Validation found problems:")
        for problem in validation_problems[:20]:
            print(f"   - {problem}")
        if len(validation_problems) > 20:
            print(f"   ... and {len(validation_problems) - 20} more.")

    if unscheduled:
        print("\nWARNING: Some sessions could not be scheduled. "
              "See the Unscheduled sheet.")

    if stats["status"] != "OPTIMAL":
        print("NOTE: The solver found a feasible solution but did not "
              "prove that it is optimal, or the search ended early.")


if __name__ == "__main__":
    input_file = sys.argv[1] if len(sys.argv) > 1 else config.INPUT_FILE
    output_file = sys.argv[2] if len(sys.argv) > 2 else "timetable.xlsx"
    main(input_file, output_file)